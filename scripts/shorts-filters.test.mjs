import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
test('reader can combine topic, year, source and full-text search, then reset', async () => {
  const fields = Object.fromEntries(['search', 'source', 'year', 'topic'].map((key) => [`[data-short-${key}]`, { value: '' }]));
  const listeners = {};
  const form = { hidden: true, querySelector: (selector) => fields[selector], addEventListener: (name, callback) => { listeners[name] = callback; } };
  const card = (source, year, topic, text) => ({ dataset: { source, year, topics: topic }, textContent: 'Title', hidden: false, querySelector: () => ({ content: { textContent: text } }) });
  const cards = [card('profile', '2024', 'ai-teaching', '評量與 Python'), card('profile', '2026', 'family-learning', '農場故事'), card('original', '2024', 'ai-teaching', 'Classroom projects')];
  const count = {};
  const empty = {};
  const document = { documentElement: { lang: 'zh-Hant' }, querySelector: (selector) => ({ '[data-short-filters]': form, '[data-short-count]': count, '[data-short-empty]': empty })[selector], querySelectorAll: () => cards };
  vm.runInNewContext(await readFile(new URL('../assets/shorts.js', import.meta.url), 'utf8'), { document, setTimeout: (callback) => callback() });
  assert.equal(form.hidden, false);
  fields['[data-short-topic]'].value = 'ai-teaching';
  fields['[data-short-year]'].value = '2024';
  listeners.change();
  assert.deepEqual(cards.map((item) => item.hidden), [false, true, false]);
  fields['[data-short-source]'].value = 'profile';
  fields['[data-short-search]'].value = 'ＰＹＴＨＯＮ 評量';
  listeners.input();
  assert.deepEqual(cards.map((item) => item.hidden), [false, true, true]);
  assert.equal(count.textContent, '1 / 3 篇短文');
  fields['[data-short-search]'].value = 'does-not-exist';
  listeners.input();
  assert.equal(empty.hidden, false);
  for (const field of Object.values(fields)) field.value = '';
  listeners.reset();
  assert.ok(cards.every((item) => !item.hidden));
  assert.equal(empty.hidden, true);
  let prevented = false;
  listeners.submit({ preventDefault: () => { prevented = true; } });
  assert.equal(prevented, true);
});
